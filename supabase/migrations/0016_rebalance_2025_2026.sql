-- 2024·2025·2026년(9·10·11라운드) 가격 재조정.
-- 기존 데이터는 거래 가능한 6종목이 세 해 모두 전부 상승이라, 마지막 세 라운드가
-- "아무거나 사면 이기는" 구간이었다. 힌트를 읽고 고르는 선택이 실제로 점수에
-- 반영되도록 2024년은 4상승/2하락, 2025·2026년은 각각 3상승/3하락으로 바꾼다.
--
-- 성균반도체의 2024년 +81%도 함께 낮춘다. 한 라운드에 자산이 1.8배가 되면 그 해
-- 한 종목이 대회 전체를 결정해 버리고, 실제 2024년 국내 반도체 주가 흐름과도
-- 맞지 않는다. 같은 업종인 숭실전자(+32%)와 비슷한 +35% 수준으로 맞춘다.
--
-- 2024년: AI 반도체는 강세였지만 중국 소비 둔화로 화장품·면세 채널이 무너졌고
--   고물가로 의류 지출이 줄었다. 그래서 경희한방과 이화패션만 하락한다.
-- 2025년: 반도체·메모리가 AI 수요로 계속 강세, K-뷰티 수출은 사상 최대.
--   반대로 극장·내수 의류·광고 용역은 부진했다.
-- 2026년: 반도체 사이클 조정 시나리오. 직전 해 가장 많이 오른 성균반도체가
--   꺾이고, 같은 반도체인 숭실전자는 계속 오른다. "작년에 오른 걸 사면 된다"와
--   "같은 업종은 같이 움직인다"를 둘 다 빗나가게 해 마지막 라운드를 만든다.
--
-- 중앙미디어(1,000원)·시립도시개발(1,500원)은 이미 상장폐지 상태라 건드리지 않는다.

update stock_prices sp
set price = v.price
from (values
  -- 2024년 (2023년 종가 대비) — 4상승 / 2하락
  ('성균반도체',   2024,  78000),  --  58,000 -> +34.5%  AI 반도체 수요로 실적 개선 (기존 +81%에서 하향)
  ('이화패션',     2024,  26500),  --  30,000 -> -11.7%  고물가에 의류 지출 감소
  ('경희한방',     2024,  45000),  --  51,000 -> -11.8%  중국 소비 둔화, 면세 채널 부진
  -- 2025년 (2024년 종가 대비) — 3상승 / 3하락
  ('성균반도체',   2025, 100000),  --  78,000 -> +28.2%  HBM·AI 수요로 파운드리 풀가동
  ('숭실전자',     2025, 106000),  --  87,000 -> +21.8%  메모리 업사이클, 수출 단가 상승
  ('경희한방',     2025,  52000),  --  45,000 -> +15.6%  K-뷰티 수출 사상 최대
  ('동국필름',     2025,  20500),  --  25,500 -> -19.6%  극장 관객 회복 정체
  ('이화패션',     2025,  22500),  --  26,500 -> -15.1%  내수 소비 침체 장기화
  ('숙명디자인',   2025,  28500),  --  32,500 -> -12.3%  광고·디자인 용역 발주 축소
  -- 2026년 (2025년 종가 대비) — 3상승 / 3하락
  ('동국필름',     2026,  26000),  --  20,500 -> +26.8%  기저효과 + 텐트폴 흥행
  ('이화패션',     2026,  28000),  --  22,500 -> +24.4%  리브랜딩 성공, 해외 판매 확대
  ('숭실전자',     2026, 124000),  -- 106,000 -> +17.0%  메모리 계약단가 강세 지속
  ('숙명디자인',   2026,  25000),  --  28,500 -> -12.3%  광고 시장 회복 지연
  ('경희한방',     2026,  45000),  --  52,000 -> -13.5%  경쟁 심화, 기저효과
  ('성균반도체',   2026,  82000)   -- 100,000 -> -18.0%  슈퍼사이클 뒤 재고조정
) as v(stock_name, year, price)
join stocks s on s.name = v.stock_name
join rounds r on r.year_label = v.year
where sp.stock_id = s.id and sp.round = r.round;

-- 가격을 바꿨으므로 이미 기록된 라운드별 자산 스냅샷과 어긋나지 않도록 대회를 초기화한다.
delete from participants;   -- cascades holdings, asset_history
update game_state set current_round = 0, is_paused = false, updated_at = now() where id = 1;
